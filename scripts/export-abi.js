// Copies the compiled ABI into the frontend so the two never drift apart.
const fs = require("fs");
const path = require("path");
const artifact = require("../artifacts/contracts/CertificateRegistry.sol/CertificateRegistry.json");
const out = path.join(__dirname, "..", "frontend", "src", "lib", "abi.js");
fs.writeFileSync(out, `// AUTO-GENERATED by scripts/export-abi.js — do not edit\nexport const ABI = ${JSON.stringify(artifact.abi, null, 2)};\n`);
console.log("ABI written to", out);
